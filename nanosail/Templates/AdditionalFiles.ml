(*

   The files that the translator writes in addition to the outputs of the templates,
   for preserve-file-structure (see docs/usage.md#preserve-file-structure):

     machine_decl.v   the declarations of the functions, next to machine.v
     Machine/dir/foo.v    the bodies of the functions of dir/foo.sail

   where machine.v is the output of the template that generates (program-translation).

   These files Require the base library, the output of the template that generates
   (base-translation). Templates are processed one by one, and that template may come
   after the one with (program-translation), so the files are generated when
   (program-translation) is evaluated, and written once all templates are processed (write_all).

*)
open ExtBase


(* The output file of the template being processed *)
let current_output_file : string option ref = ref None


(* The output file of the template that generated (base-translation), if any *)
let base_output_file : string option ref = ref None


(* Files generated by (program-translation), to be written by write_all *)
type pending =
  {
    directory            : string;               (* the directory of machine.v *)
    declarations_library : string;               (* machine_decl *)
    declarations         : string;               (* without the Require of the base library *)
    sail_files_directory : string;               (* Machine *)
    sail_files           : (NanosailToMicrosail.FileStructure.ModulePath.t * string) list (* contents without the Require of the base library *)
  }


let pending : pending list ref = ref []


(* Forgets the files of an earlier run (for tests, which run several translations in one process) *)
let reset () : unit =
  current_output_file := None;
  base_output_file    := None;
  pending             := []


let library_name_of_output_file (output_file : string) : string =
  let base_name = Stdlib.Filename.basename output_file
  in
  Option.value ~default:base_name @@ String.chop_suffix base_name ~suffix:".v"


(* Called by (base-translation): remembers which file holds the base library *)
let record_base_translation () : unit =
  match !current_output_file with
  | Some output_file -> begin
      (* (base-html-translation) and HTML templates do not produce a library *)
      if String.is_suffix output_file ~suffix:".v"
      then base_output_file := Some output_file
    end
  | None -> ()


(*
   Called by (program-translation) with preserve-file-structure: generates all files of the
   program, keeps the declarations and the files of the Sail files for write_all, and
   returns the contents of the template's own output (the program module).
*)
let generate_program_files
    ~(string_of_document : PP.t -> string                         )
    (translation         : NanosailToMicrosail.Katamaran.katamaran) : string
  =
  let output_file =
    match !current_output_file with
    | Some output_file -> output_file
    | None             -> failwith "preserve-file-structure: (program-translation) must be used in a template"
  in
  let declarations_library = library_name_of_output_file output_file ^ "_decl"
  in
  (* the names of the program's own files, which the files of the Sail files cannot have *)
  let reserved_names =
    declarations_library :: List.map Configuration.(get template_translations) ~f:(fun (translation : Configuration.template_translation) ->
        library_name_of_output_file translation.output_filename
      )
  in
  let files : NanosailToMicrosail.ProgramModule.files =
    NanosailToMicrosail.GenerationContext.generate translation#program @@ translation#pp_program_files ~declarations_library ~reserved_names
  in
  pending := {
      directory    = Stdlib.Filename.dirname output_file;
      declarations_library;
      declarations = string_of_document files.declarations;
      sail_files_directory = files.sail_files_directory;
      sail_files   = List.map files.sail_files ~f:(fun (module_path, document) -> (module_path, string_of_document document));
    } :: !pending;
  string_of_document files.assembly


(* Creates a directory and the directories above it, as far as they do not exist yet *)
let rec ensure_directory (path : string) : unit =
  if not (Stdlib.Sys.file_exists path)
  then begin
    ensure_directory (Stdlib.Filename.dirname path);
    Stdlib.Sys.mkdir path 0o755
  end
  else if not (Stdlib.Sys.is_directory path)
  then failwith @@ Printf.sprintf "preserve-file-structure: %s exists but is not a directory" path


(* The .v files in a directory and its subdirectories, as paths relative to it *)
let rec rocq_files_below (directory : string) : string list =
  List.concat_map (List.sort ~compare:String.compare @@ Array.to_list @@ Stdlib.Sys.readdir directory) ~f:(fun entry ->
      let path = Stdlib.Filename.concat directory entry
      in
      if Stdlib.Sys.is_directory path
      then List.map (rocq_files_below path) ~f:(Stdlib.Filename.concat entry)
      else if String.is_suffix entry ~suffix:".v"
      then [ entry ]
      else []
    )


let write (pending : pending) : unit =
  let base_library =
    match !base_output_file with
    | None -> failwith "preserve-file-structure: no template generates (base-translation) into a .v file, which the generated files need to Require"
    | Some base_output_file -> begin
        if
          not @@ String.equal (Stdlib.Filename.dirname base_output_file) pending.directory
        then
          failwith @@ Printf.sprintf
            "preserve-file-structure: the output of (base-translation), %s, must be in the same directory as that of (program-translation), %s"
            base_output_file pending.directory;
        library_name_of_output_file base_output_file
      end
  in
  (* the generated documents do not end in a newline, unlike the outputs of templates *)
  let with_require (mode : string) (libraries : string list) (contents : string) : string =
    Printf.sprintf "Require %s %s.\n\n%s\n" mode (String.concat ~sep:" " libraries) contents
  in
  Stdio.Out_channel.write_all
    (Stdlib.Filename.concat pending.directory (pending.declarations_library ^ ".v"))
    ~data:(with_require "Export" [ base_library ] pending.declarations);
  let generated_files =
    List.map pending.sail_files ~f:(fun (module_path, _) -> NanosailToMicrosail.FileStructure.ModulePath.to_file ~directory:pending.sail_files_directory module_path)
  in
  ensure_directory @@ Stdlib.Filename.concat pending.directory pending.sail_files_directory;
  List.iter pending.sail_files ~f:(fun (module_path, contents) ->
      let path = Stdlib.Filename.concat pending.directory (NanosailToMicrosail.FileStructure.ModulePath.to_file ~directory:pending.sail_files_directory module_path)
      in
      ensure_directory (Stdlib.Filename.dirname path);
      Stdio.Out_channel.write_all path ~data:(with_require "Import" [ base_library; pending.declarations_library ] contents)
    );
  (* the files of Sail files that no longer have functions (or no longer exist) would otherwise still be compiled *)
  let directory = pending.sail_files_directory
  in
  List.iter (rocq_files_below (Stdlib.Filename.concat pending.directory directory)) ~f:(fun relative ->
      let file = Stdlib.Filename.concat directory relative
      in
      if not @@ List.mem generated_files file ~equal:String.equal
      then begin
        Logging.info [%here] @@ lazy (PP.format "Removing %s, which is no longer generated" file);
        Stdlib.Sys.remove (Stdlib.Filename.concat pending.directory file)
      end
    )


(* Writes the files generated by (program-translation), once all templates are processed *)
let write_all () : unit =
  List.iter (List.rev !pending) ~f:write;
  pending := []
